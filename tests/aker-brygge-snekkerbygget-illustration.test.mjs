import {test} from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import crypto from "node:crypto";
import sharp from "sharp";
const sha=b=>crypto.createHash("sha256").update(b).digest("hex");
test("Snekkerbygget source-bounded original illustration, never a false photo",async()=>{
 const report=JSON.parse(await fs.readFile("reports/place-production/aker-brygge-snekkerbygget-illustration-candidate-2026-11-19.json","utf8"));
 const audit=JSON.parse(await fs.readFile("reports/place-production/aker-brygge-structures-source-audit-2026-11-19.json","utf8"));
 const candidate=audit.candidates.find(c=>c.id==="aker_brygge_snekkerbygget");
 assert.equal(candidate?.illustrationCandidate?.publishable,false);
 assert.equal(candidate?.illustrationCandidate?.label,"ILLUSTRASJON");
 assert.equal(report.structureId,"aker_brygge_snekkerbygget");
 assert.equal(report.assetKind,"original_architectural_illustration_not_a_photograph");
 assert.equal(report.exactBuildingPhotographicMatch,false);
 assert.equal(report.publishable,false);
 assert.equal(report.visualApproval,false);
 assert.equal(report.placecardStructuresEnabled,false);
 assert.equal(report.vFerdig,false);
 assert.equal(report.sourcePath,"bilder/kort/structures/source/aker_brygge/snekkerbygget_architectural_illustration.svg");
 assert.equal(report.candidatePath,"bilder/kort/structures/candidates/aker_brygge/snekkerbygget_architectural_illustration.webp");
 assert.match(report.likenessLimit,/NOT verified as an exact facade elevation/);
 assert.match(report.notes.join(" "),/municipal Havnepromenade/i);
 const svg=await fs.readFile(report.sourcePath),webp=await fs.readFile(report.candidatePath);
 assert.equal(sha(svg),report.sourceSha256);
 assert.equal(sha(webp),report.candidateSha256);
 assert.ok(!svg.toString("utf8").includes("href=\"https:"));
 const a=await sharp(svg).metadata(),b=await sharp(webp).metadata();
 assert.deepEqual([a.width,a.height,a.format],[1400,900,"svg"]);
 assert.deepEqual([b.width,b.height,b.format],[1200,800,"webp"]);
 assert.ok(report.candidateBytes>10000&&report.candidateBytes<1500000);
});
