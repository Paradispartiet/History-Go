import {test} from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import crypto from "node:crypto";
import sharp from "sharp";
const digest=(b,method="sha256")=>crypto.createHash(method).update(b).digest("hex");
test("Aker Brygge historic halls: genuine licensed overview, no individual mislabeling",async()=>{
 const j=JSON.parse(await fs.readFile("reports/place-production/aker-brygge-verkstedhallene-licensed-overview-2026-11-19.json","utf8"));
 const audit=JSON.parse(await fs.readFile("reports/place-production/aker-brygge-structures-source-audit-2026-11-19.json","utf8"));
 assert.equal(j.placeId,"aker_brygge");
 assert.equal(audit.publishable,false);
 assert.equal(j.accurateScope,"shared_hall_environment_only");
 assert.equal(j.sourcePage,"https://commons.wikimedia.org/wiki/File:Bryggegata,_Oslo_(2022)_(3).jpg");
 assert.equal(j.originalSha1,"eb45a0f9ea81d218715a56eddb300d132e4accf7");
 assert.equal(j.license,"CC BY-SA 4.0");
 assert.equal(j.author,"Ssu");
 assert.equal(j.visualReview,false);
 assert.equal(j.individualBuildingIdentified,false);
 assert.equal(j.publishable,false);
 assert.equal(j.placecardStructuresEnabled,false);
 assert.equal(j.editorialApproval,false);
 assert.equal(j.vFerdig,false);
 assert.deepEqual(j.prohibitedIndividualAssignments,["aker_brygge_verkstedhallen","aker_brygge_maskinhallen","aker_brygge_dieselmotorverksted"]);
 const a=await fs.readFile(j.originalPath),b=await fs.readFile(j.candidatePath);
 assert.equal(digest(a,"sha1"),j.originalSha1);
 assert.equal(digest(a),j.originalSha256);
 assert.equal(digest(b),j.candidateSha256);
 const im=await sharp(a).metadata(),om=await sharp(b).metadata();
 assert.deepEqual([im.width,im.height,im.format],[3767,2825,"jpeg"]);
 assert.deepEqual([om.width,om.height,om.format],[1200,900,"webp"]);
 assert.ok(j.candidateBytes>30000&&j.candidateBytes<2000000);
 assert.match(j.transformation,/without hard crop or zoom/);
});
