import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import test from "node:test";
import sharp from "sharp";
const read=f=>JSON.parse(fs.readFileSync(f,"utf8"));
const r=read("reports/place-production/det-norske-teatret/20261020/object-costume-visual-review-c38.json");
const o=read("reports/place-production/det-norske-teatret/20261020/objects-c31-candidates.json");
const w=read("reports/place-production/det-norske-teatret-workcard-current.json");
const p=read("reports/place-production/det-norske-teatret/20261020/object-image-c32-generated.json");
test("C38 exact identified museum costume media is genuine unmodified 800x800 WebP",async()=>{
 const bytes=fs.readFileSync(p.asset_path);
 const md=await sharp(bytes).metadata();
 assert.equal(md.format,"webp");
 assert.equal(md.width,800);assert.equal(md.height,800);
 assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),p.asset_sha256);
 assert.equal(r.asset_sha256,p.asset_sha256);
 assert.equal(r.candidate_id,"dnt_costume_madame_de_sade_1989_tm01641");
 assert.equal(r.museum_accession,"TM.01641.A-C");
 assert.equal(r.source_creator,"Lone Lunde");
 assert.equal(r.source_license,"CC BY-SA 4.0");
 assert.equal(r.verification_method.includes("Direct inspection"),true);
 assert.equal(r.observations.full_garment_visible,true);
 assert.match(r.observations.environment,/not a scene from theatrical performance/i);
 assert.equal(r.review_decision,"APPROVE_SINGLE_IMAGE_COMPOSITION_FOR_FUTURE_OBJECT_MEMBER");
});
test("C38 approved photograph does not declare whole Objects collection ready",()=>{
 const item=o.candidates.find(x=>x.id===r.candidate_id);
 assert.equal(item.rights.visual_qa_c38.status,"PASS_AS_SINGLE_OBJECT_PHOTO_ONLY");
 assert.equal(item.rights.visual_qa_c38.sha256,r.asset_sha256);
 assert.equal(item.publication_status,"BLOCKED");
 assert.equal(r.collection_decision,"KEEP_BLOCKED_SECOND_DISTINCT_RIGHTS_CLEARED_OBJECT_AND_UI_GATE_MISSING");
 assert.equal(o.counts.source_images_cleared_cc,1);
 assert.equal(o.counts.local_rights_checked_assets_staged,1);
 assert.equal(o.counts.local_member_images_published,0);
 assert.equal(o.counts.published_objects,0);
 assert.equal(w.collections.objects.status,"PASS");
 assert.equal(w.status,"in_progress");
 assert.deepEqual(w.placecard_collections_publishable_now,["objects"]);
 assert.ok(w.checkpoints.some(x=>x.id==="costume_actual_asset_visual_qa_c38"));
});
