'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html><body></body>', { url: 'https://example.test', runScripts: 'outside-only' });
const w = dom.window;
const wallet = { balance: 20000, nok_v1: { active: true, version: 1 } };
w.CivicationState = { getWallet: () => wallet };
w.localStorage.setItem('hg_capital_v1', JSON.stringify({ economic: 50 }));
w.localStorage.setItem('civi_home_v1', JSON.stringify({ currentDistrictId: 'sagene', home: { district: 'sagene' } }));
w.eval(fs.readFileSync('js/Civication/ui/CivicationHome.js', 'utf8'));
const savedHome = w.localStorage.getItem('civi_home_v1');
const savedWallet = JSON.stringify(wallet);
assert.equal(w.CivicationHome.applyRentTick(true).reason, 'NOK_WALLET_BILLING');
assert.equal(w.CivicationHome.applyHousingPeriodCosts(true).reason, 'NOK_WALLET_BILLING');
assert.equal(w.localStorage.getItem('hg_capital_v1'), '{"economic":50}');
assert.equal(w.localStorage.getItem('civi_home_v1'), savedHome);
assert.equal(JSON.stringify(wallet), savedWallet, 'old rent APIs neither debit nor create new wallet invoices');
wallet.nok_v1.active = false;
w.CivicationHome.applyRentTick(true);
assert.equal(JSON.parse(w.localStorage.getItem('hg_capital_v1')).economic, 46, 'legacy players retain current rent behavior');
w.CivicationHome.applyHousingPeriodCosts(true);
assert.equal(JSON.parse(w.localStorage.getItem('hg_capital_v1')).economic, 42);
console.log('PASS: both legacy rent paths skip NOK players without writes; existing players retain old behavior');
dom.window.close();
