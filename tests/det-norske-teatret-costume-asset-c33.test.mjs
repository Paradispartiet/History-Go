import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import test from "node:test";
import sharp from "sharp";
const img="bilder/objects/det_norske_teatret/madame_de_sade_1989_tm01641.webp";
const r="reports/place-production/det-norske-teatret/20261020/object-image-c32-generated.json";
const registry="reports/place-production/det-norske-teatret/20261020/objects-c31-candidates.json";
const place="data/places/scenekunst/oslo/places_scenekunst/det_norske_teatret.json";
const workcard="reports/place-production/det-norske-teatret-workcard-current.json";
const read=p=>JSON.parse(fs.readFileSync(p,"utf8"));
test("C33 original asset SHA, dimensions and attribution match the source-checked provenance",async()=>{
 const rep=read(r),bytes=fs.readFileSync(img);
 const m=await sharp(bytes).metadata();
 assert.equal(bytes.length,81576);
 assert.equal(m.format,"webp");
 assert.equal(m.width,800);
 assert.equal(m.height,800);
 assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),rep.asset_sha256);
 assert.equal(rep.asset_sha256,"a4c04b491558f65551385f3e98651e599319e5e6a576f80ae33c105bef57c31f");
 assert.equal(rep.source_sha256,"eb859938f5d7ced4c2475c70a6befae919364088af8087bc0aae80760f0091ce");
 assert.equal(rep.museum_accession,"TM.01641.A-C");
 assert.equal(rep.creator,"Lone Lunde");
 assert.equal(rep.license,"CC BY-SA 4.0");
 assert.equal(rep.status,"LOCAL_IMAGE_IN_DRAFT_NOT_CANONICAL");
 assert.equal(rep.asset_path,img);
 assert.match(rep.transformation,/No content cropping/);
});
test("C33 asset publication is not a phantom canonical Objects or PlaceCard collection",()=>{
 const reg=read(registry),p=read(place),w=read(workcard);
 assert.equal(p.id,"det_norske_teatret");
 assert.equal(p.objects?.length, 2, "C50 registers two separately verified canonical Objects");
 assert.equal(reg.counts.candidates,3);
 assert.equal(reg.counts.local_rights_checked_assets_staged,1);
 assert.equal(reg.counts.published_objects,0);
 assert.equal(reg.counts.local_member_images_published,0);
 assert.equal(w.collections.objects.status,"PASS");
 assert.equal(w.status,"in_progress");
 assert.deepEqual(w.placecard_collections_publishable_now,["objects"]);
 const ids=reg.candidates.map(x=>x.id);
 assert.equal(new Set(ids).size,3);
 const costume=reg.candidates.find(x=>x.museum_accession==="TM.01641.A-C");
 assert.equal(costume.rights.local_draft_asset,img);
 assert.equal(costume.rights.local_draft_provenance,r);
 assert.equal(costume.publication_status,"BLOCKED");
 assert.ok(w.checkpoints.some(x=>x.id==="costume_source_asset_materialized_c33"));
});
