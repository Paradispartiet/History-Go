import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import sharp from "sharp";
import test from "node:test";
const asset="bilder/places/det_norske_teatret_front_bjoertvedt_2013.webp";
const report="reports/place-production/det-norske-teatret/20261020/front-image-c34-generated.json";
const place="data/places/scenekunst/oslo/places_scenekunst/det_norske_teatret.json";
const card="reports/place-production/det-norske-teatret-workcard-current.json";
const read=f=>JSON.parse(fs.readFileSync(f,"utf8"));
test("DNT C35 licensed frontImage candidate has correct actual bytes, orientation and independent source",async()=>{
 const r=read(report),p=read(place);
 const bytes=fs.readFileSync(asset),m=await sharp(bytes).metadata();
 assert.equal(bytes.length,183018);
 assert.equal(m.format,"webp");
 assert.equal(m.width,900);
 assert.equal(m.height,1350);
 assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),r.asset_sha256);
 assert.equal(r.asset_sha256,"14a88af025f76ba368fffe89f348e6bf8eb9fcc56cda067aeb1e0df5fb1e46f2");
 assert.equal(r.source_sha256,"c4ef9e6e2c758090a3d2976b9293dc6b3e7fc4652550f8416fb54d7ca21c28cf");
 assert.equal(r.license,"CC BY-SA 3.0");
 assert.equal(r.creator,"Bjoertvedt");
 assert.equal(r.source_file,"File:Oslo Det norske teatret IMG 0553.JPG");
 assert.equal(r.source_date,"2013-12-15");
 assert.equal(r.status,"DRAFT_PHOTO_NOT_CANONICAL");
 assert.equal(r.asset_path,asset);
 assert.notEqual(r.source_file,p.imageMeta.fileTitle);
 assert.notEqual(r.creator,p.imageMeta.author);
 assert.notEqual(asset,p.image);
 assert.notEqual(asset,p.cardImage);
});
test("C35 original photo now has an explicit, reviewed C36 canonical binding without full Place closeout",()=>{
 const w=read(card),p=read(place);
 assert.equal(p.frontImage,asset);
 assert.equal(read("reports/place-production/det-norske-teatret/20261020/front-image-c36-visual-review.json").decision,"APPROVE_PHOTO_FOR_CANONICAL_FRONTIMAGE_BINDING");
 assert.equal(w.status,"in_progress");
 assert.equal(w.collections.objects.status,"PASS");
 assert.deepEqual(w.placecard_collections_publishable_now,["objects"]);
 assert.ok(w.checkpoints.some(x=>x.id==="front_facade_media_staged_c35"));
});
