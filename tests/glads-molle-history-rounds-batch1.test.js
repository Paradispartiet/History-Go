const validBadges=new Set(readJson('data/badges/historie.json').sub);
const index=readJson('data/places/natur/oslo/places_oslo_natur_akerselvarute_index.json').find(x=>x.id==='glads_molle');
const manifest=readJson('data/places/natur/oslo/places_oslo_natur_akerselvarute_manifest.json').places.find(x=>x.id==='glads_molle');
const peopleManifest=readJson('data/people/manifest.json');
assert.strictEqual(place.id,'glads_molle');
assert.strictEqual(place.category,'historie');
assert.deepStrictEqual([place.lat,place.lon,place.r,place.year],[59.932034,10.757865,120,1736]);
assert.strictEqual(place.coordStatus,'verified_geometry');
assert.strictEqual(place.coordType,'building_center');
assert.strictEqual(place.sourceObjectId,'kulturminnesok:86157');
assert.strictEqual(place.address.street,'Sandakerveien');
assert.strictEqual(place.address.number,'10A');
for(const key of ['rounds','rundinger','routes','tasks','training','play','flora','fauna']) assert(!Object.prototype.hasOwnProperty.call(place,key),`forbudt felt ${key}`);
assert(peopleManifest.files.includes(peopleNaturPath.replace(/^data\//,'')));
assert(peopleManifest.files.includes(peopleBusinessPath.replace(/^data\//,'')));
for(const p of [iver,fredrik]){assert(p&&p.placeId===place.id&&p.places.includes(place.id));assert(p.source_urls.length>=3);assert.strictEqual(p.image,'');assert.strictEqual(p.cardImage,'');}
assert(halvor&&halvor.places.includes(place.id)&&halvor.source_urls.length>=5);
assert(storyManifest.files.some(x=>x.path===storyPath&&x.entity_id===place.id));
assert(story&&story.place_id===place.id&&story.person_id===iver.id);
assert(story.related_people.includes(fredrik.id)&&story.related_people.includes(halvor.id));
assert(story.sources.length>=10);
assert(article&&article.sources.length>=10&&article.facts.length>=9&&article.chronology.length>=9);
assert(index&&manifest);
assert.deepStrictEqual([index.lat,index.lon,index.r,index.year],[place.lat,place.lon,place.r,place.year]);
assert.strictEqual(index.coordStatus,'verified_geometry');
const roundContent={people:[iver,fredrik,halvor],works:place.works,badges:place.underbadge_ids,før_nå:place.for_na,civication:place.civication_store,brands:place.brands,nature:place.nature_profile,fortellinger:[story],leksikon:[article]};
assert.deepStrictEqual(Object.keys(roundContent),expectedRounds);
for(const [id,v] of Object.entries(roundContent)){const filled=Array.isArray(v)?v.length>0:Boolean(v&&typeof v==='object');assert(filled,`mangler ${id}`);}
assert(place.externalLinks.length>=10&&place.externalLinks.every(x=>/^https:\/\//.test(x.url)));
assert(place.underbadge_ids.length>=6&&place.underbadge_ids.every(x=>validBadges.has(x)));
assert(place.works.length>=10);
assert(place.civication_store.length>=4&&place.civication_store.every(x=>x.physicalObject&&x.placeSpecific));
assert(place.brands.length>=10);
assert(place.for_na.before&&place.for_na.now&&place.for_na.look_for.length>=7);
assert(place.nature_profile.summary.length>=550&&place.nature_profile.themes.length>=7);
