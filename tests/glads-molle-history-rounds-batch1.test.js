const assert = require('assert');
const fs = require('fs');
const path = require('path');
const repo = path.resolve(__dirname, '..');
const readJson = p => JSON.parse(fs.readFileSync(path.join(repo, p), 'utf8'));
const expectedRounds = ['people','works','badges','før_nå','civication','brands','nature','fortellinger','leksikon'];
const runtime = fs.readFileSync(path.join(repo, 'js/ui/place-card.js'),'utf8');
const match = runtime.match(/historie:\s*\[([^\]]+)\]/);
assert(match);
assert.deepStrictEqual(JSON.parse(`[${match[1]}]`), expectedRounds);
const placePath='data/places/natur/oslo/places_oslo_natur_akerselvarute/glads_molle.json';
const place=readJson(placePath);
const peopleNaturPath='data/people/natur/oslo/people_natur_oslo.json';
const peopleBusinessPath='data/people/naeringsliv/oslo/people_naeringsliv_oslo.json';
const peopleNatur=readJson(peopleNaturPath);
const peopleBusiness=readJson(peopleBusinessPath);
const iver=peopleNatur.find(x=>x.id==='iver_elieson_glads_molle');
const fredrik=peopleNatur.find(x=>x.id==='fredrik_glad_glads_molle');
const halvor=peopleBusiness.find(x=>x.id==='halvor_schou');
const storyPath='data/stories/stories_glads_molle.json';
const story=readJson(storyPath)[0];
const storyManifest=readJson('data/stories/stories_manifest_natur_batch_01.json');
const articlePath='data/leksikon/places/oslo/historie/leksikon_oslo_historie_batch2.json';
