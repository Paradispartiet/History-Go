import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const read=path=>JSON.parse(readFileSync(new URL('../'+path,import.meta.url),'utf8'));
const path='bilder/merker/film_tv/undermerker/spillefilm-brodert-v2.webp';
const sha='6d2bb5097dd1c0de21e817358ef2d45e1ddd75daaf8b400eaf38147997387db7';
test('Spillefilm v2 verified WebP and only active Film & TV underbadge',()=>{
 const film=read('data/badges/film_tv.json');
 const manifest=read('data/badges/underbadge_batch01_production.json');
 const a=manifest.families.film_tv.assets.find(x=>x.id==='spillefilm');
 const v2=a.replacementCandidate;
 assert.equal(film.image,'bilder/merker/film_tv-brodert-v5.webp');
 assert.equal(film.color.toUpperCase(),'#C2188B');
 assert.equal(film.secondaryColor.toUpperCase(),'#E7F8FF');
 assert.deepEqual(film.subBadgeImages,{spillefilm:path});
 assert.equal(a.selectedImage,path);
 assert.equal(a.status,'rework_required','original v1 remains rejected');
 assert.equal(v2.status,'active');
 assert.equal(v2.selectedImage,path);
 assert.equal(v2.visualApproved,true);
 assert.equal(v2.technicalApproved,true);
 assert.equal(v2.repositoryUploaded,true);
 assert.equal(v2.letteringInsideBorder,true);
 assert.equal(v2.bytes,510186);
 assert.equal(v2.sha256,sha);
 assert.equal(a.redesignBrief.labelInsideBorder,'SPILLEFILM');
 assert.equal(a.redesignBrief.approved,true);
 assert.ok(a.redesignBrief.strictlyAvoid.includes('movie_camera'));
 assert.ok(a.redesignBrief.strictlyAvoid.includes('contact_sheet_crop'));
 const b=readFileSync(new URL('../'+path,import.meta.url));
 assert.equal(b.length,v2.bytes);
 assert.equal(b.toString('ascii',0,4),'RIFF');
 assert.equal(b.readUInt32LE(4)+8,b.length);
 assert.equal(b.toString('ascii',8,12),'WEBP');
 assert.equal(b.toString('ascii',12,16),'VP8X');
 assert.ok(b[20]&0x10,'RGBA alpha channel');
 assert.equal(b.readUIntLE(24,3)+1,1024);
 assert.equal(b.readUIntLE(27,3)+1,1024);
 assert.equal(createHash('sha256').update(b).digest('hex'),sha);
});
test('All seven Scenekunst underbadge references and main badge are preserved',()=>{
 const scene=read('data/badges/scenekunst.json');
 assert.equal(Object.keys(scene.subBadgeImages).length,7);
 for(const id of scene.sub)assert.ok(scene.subBadgeImages[id],id);
 assert.equal(scene.image,'bilder/merker/scenekunst-brodert-v1.webp');
});
