import {test} from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import crypto from "node:crypto";
import sharp from "sharp";
const sha=(b,algorithm="sha256")=>crypto.createHash(algorithm).update(b).digest("hex");
test("Aker Brygge — Wilse 1929 drydock source authenticity and hold",async()=>{
 const r=JSON.parse(await fs.readFile("reports/place-production/aker-brygge-torrdokken-wilse-1929-image-candidate.json","utf8"));
 const a=JSON.parse(await fs.readFile("reports/place-production/aker-brygge-structures-source-audit-2026-11-19.json","utf8"));
 assert.equal(r.subjectId,"aker_brygge_torrdokken");
 assert.ok(a.candidates.some(x=>x.id===r.subjectId));
 assert.equal(r.sourcePage,"https://commons.wikimedia.org/wiki/File:Frontenac_(OB.Y3285).jpg");
 assert.equal(r.sourceSha1,"dfeb9349c60e718014e12c564702fcf306a1ec84");
 assert.equal(r.photographer,"Anders Beer Wilse (1865–1949)");
 assert.equal(r.institution,"Oslo Museum");
 assert.equal(r.accession,"OB.Y3285");
 assert.equal(r.photographDate,"1929");
 assert.equal(r.license,"CC BY-SA 4.0");
 assert.equal(r.currentStructureGeometryVerified,false);
 assert.equal(r.publishable,false);
 assert.equal(r.visualReview,false);
 assert.equal(r.placecardStructuresEnabled,false);
 assert.equal(r.vFerdig,false);
 assert.equal(r.contentUse,"historical_photo_only");
 assert.match(r.caption,/Frontenac.*1929/);
 const source=await fs.readFile(r.originalPath),webp=await fs.readFile(r.candidatePath);
 assert.equal(sha(source,"sha1"),r.sourceSha1);
 assert.equal(sha(source),r.sourceSha256);
 assert.equal(sha(webp),r.candidateSha256);
 const sm=await sharp(source).metadata(),wm=await sharp(webp).metadata();
 assert.deepEqual([sm.width,sm.height,sm.format],[1200,883,"jpeg"]);
 assert.deepEqual([wm.width,wm.height,wm.format],[1200,900,"webp"]);
 assert.ok(r.candidateBytes>30000 && r.candidateBytes<1500000);
 assert.match(r.transformation,/no crop and no extra zoom/);
});
