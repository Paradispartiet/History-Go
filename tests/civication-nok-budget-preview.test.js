'use strict';
const assert = require('node:assert/strict');
const { preview } = require('../scripts/civication-nok-budget-preview.cjs');
const c = require('../data/Civication/economy/nok-budget-prototype-2026.json');
const before = JSON.stringify(c);
const job = preview(c, { employed: true });
assert.equal(job.annualGross, 380328);
assert.ok(Math.abs(job.annualTax - 70372.808) < .001);
assert.ok(Math.abs(job.monthlyNet - 25829.59933333333) < .001);
assert.equal(job.monthlyExpenses, 21496);
assert.equal(preview(c).monthlyNet, 0);
assert.equal(preview(c).monthlyRemainder, -21496);
assert.equal(preview(c, { approvedSupportNok: 9406 }).monthlyRemainder, -12090);
assert.equal(preview(c, { employed: true, employmentPercent: 0 }).annualTax, 0);
assert.equal(preview(c, { employed: true, employmentPercent: 50 }).annualGross, 190164);
assert.throws(() => preview(c, { employmentPercent: 101 }), RangeError);
assert.throws(() => preview(c, { approvedSupportNok: -1 }), RangeError);
assert.equal(JSON.stringify(c), before);
assert.equal(c.migration.activated, false);
console.log('PASS: sourced NOK budget preview, annual tax arithmetic, part time, support and immutable inputs');
