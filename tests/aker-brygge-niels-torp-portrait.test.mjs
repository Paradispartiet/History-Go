import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import sharp from 'sharp';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const person=read('data/people/by/oslo/aker_brygge/niels_torp.json')[0];
const report=read('reports/place-production/aker-brygge-niels-torp-portrait-2026-11-21.json');
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
test('Niels Torp uses the source-identified left-hand person, with licensed original and reviewed crop',async()=>{
 const m=person.imageMeta;
 assert.equal(person.wikidataId,'Q1108975');assert.equal(person.placeId,'aker_brygge');
 assert.equal(person.image,person.cardImage);assert.equal(m.source,'wikimedia_commons');
 assert.equal(m.credit,'Norsk Form');assert.equal(m.creator,'Norsk Form');
 assert.equal(m.license,'CC BY 3.0');assert.equal(m.reviewStatus,'manually_approved');
 assert.equal(m.approvalMode,'best_available');assert.ok(m.bestAvailableReason.length>20);
 assert.match(m.disclosure,/profil/);assert.match(m.disclosure,/Opplastingsdatoen/);
 assert.equal(sha(person.image),m.assetSha256);assert.equal(sha(m.originalPath),m.sourceSha256);
 const original=await sharp(m.originalPath).metadata(),crop=await sharp(person.image).metadata();
 assert.deepEqual([original.width,original.height],[2728,1830]);
 assert.deepEqual([crop.width,crop.height],m.outputDimensions);
 assert.ok(crop.width>=900&&crop.height>crop.width);
 assert.ok(m.crop.x+m.crop.width<0.5,'The other person on the right must be excluded');
 const c=read('data/people/people_image_candidates.json').find(c=>c.candidateId===m.candidateId);
 assert.equal(c.personId,person.id);assert.equal(c.approved,true);assert.deepEqual(c.crop,m.crop);
 assert.deepEqual(report.imageMeta,m);assert.equal(report.vFerdig,false);
 const ledger=read('data/people/people_image_attributions.json').filter(a=>a.personId===person.id);
 assert.equal(ledger.length,1);assert.equal(ledger[0].file,person.image);assert.equal(ledger[0].license,m.license);
 assert.ok(person.sources.some(s=>s.label.includes('Norsk Form')&&s.label.includes('utsnitt')&&s.url===m.sourcePage));
 assert.ok(person.sources.some(s=>s.url===m.licenseUrl));
});
test('The portrait reaches People shards, Aker Brygge and Civication without changing membership',()=>{
 const runtime=read('data/runtime/place-open/aker_brygge.json');
 assert.deepEqual(runtime.people.map(p=>p.id),['olav_thon_eiendom_og_handel','stein_erik_hagen_handel','tinashe_williamson','hariton_pushwagner','niels_torp']);
 assert.deepEqual(runtime.people.find(p=>p.id===person.id),person);
 const all=read('data/runtime/people-all.json').files.flatMap(f=>read(f));
 assert.deepEqual(all.find(p=>p.id===person.id),person);
 const index=read('data/Civication/historyPeople_index.json').categories.by.find(p=>p.id===person.id);
 assert.equal(index.image,person.image);assert.equal(index.cardImage,person.image);
 assert.deepEqual(runtime.brands.map(b=>b.id),['cos','olivia','rorbua','tiger_of_sweden','wiersholm']);
 assert.deepEqual(runtime.place.structures.map(s=>s.id),['aker_brygge_verkstedhallene_miljo','aker_brygge_torrdokken_historisk_1929']);
 assert.equal(read('reports/place-production/aker-brygge-workcard-current.json').status,'v1_verified');
});
