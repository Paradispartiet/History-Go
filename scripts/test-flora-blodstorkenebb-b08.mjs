import assert from "node:assert/strict";import fs from "node:fs";import crypto from "node:crypto";import vm from "node:vm";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
const record=JSON.parse(read("data/natur/flora/illustration-quality-blodstorkenebb-20261031.json"));const a=record.items[0],id="emne_flora_blodstorkenebb";
assert.equal(record.items.length,1);assert.equal(record.baselineApproved,19);assert.equal(record.approvedCountAfterRelease,20);
assert.equal(a.catalogId,id);assert.equal(a.scientificName,"Geranium sanguineum");assert.equal(a.reviewStatus,"approved");assert.equal(a.approvedForPublication,true);
assert(a.sourceReferences.length>=2&&a.observations.length>100&&a.limitations.length>80);
assert(a.visualChecks.transparent&&a.visualChecks.blackBackgroundReviewed&&a.visualChecks.whiteBackgroundReviewed);
const catalog=JSON.parse(read("data/natur/flora/blomster.json"));
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
assert.equal(catalog.find(x=>x.id===id)?.latin,a.scientificName);
assert.equal(runtime.find(x=>x.id===id)?.latin,a.scientificName);
const photos={window:{}};vm.runInNewContext(read("js/ui/nature-flora-photographs.js"),photos);
assert.equal(photos.window.HG_NATURE_FLORA_PHOTOS.get(id)?.scientificName,a.scientificName);
const ctx={window:{}};vm.runInNewContext(read("js/ui/nature-flora-approved.js"),ctx);
const approved=ctx.window.HG_NATURE_FLORA_APPROVED;assert(approved.count >= 22);
assert.equal(approved.get(id)?.src,a.src);assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
const b=fs.readFileSync(new URL("../"+a.src,import.meta.url));
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");assert.equal(b.toString("ascii",8,12),"WEBP");assert.equal(b.toString("ascii",12,16),"VP8X");
assert((b[20]&0x10)!==0,"WebP must have alpha");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],a.dimensions);
console.log("Blodstorkenebb: 601524-byte WebP, SHA-256, Git blob, alpha, canonical species and licensed photo fallback OK; 20 approvals");
