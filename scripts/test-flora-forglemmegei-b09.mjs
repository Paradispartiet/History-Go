import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root = new URL("../", import.meta.url);
const read = p => fs.readFileSync(new URL(p, root), "utf8");
const review = JSON.parse(read("data/natur/flora/illustration-quality-forglemmegei-20261101.json"));
const [a] = review.items, id = "emne_flora_forglemmegei";
assert.equal(review.schema, "history-go-flora-single-species-review-v1");
assert.equal(review.baselineApproved, 27);
assert.equal(review.approvedCountAfterRelease, 28);
assert.equal(review.items.length, 1);
assert.equal(a.catalogId, id);
assert.equal(a.scientificName, "Myosotis spp.");
assert.equal(a.taxonomicScope, "genus-representative");
assert.equal(a.reviewStatus, "approved");
assert.equal(a.botanicalVisualDecision, "visually_recognizable_genus_field_guide_level");
assert.equal(a.approvedForPublication, true);
assert(a.sourceReferences.length >= 3 && a.observations.length > 160 && a.limitations.length > 150);
assert(a.visualChecks.originalAlphaVerified && a.visualChecks.blackBackgroundReviewed && a.visualChecks.whiteBackgroundReviewed);
const catalog=JSON.parse(read("data/natur/flora/blomster.json"));
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
assert.equal(catalog.find(x=>x.id===id)?.latin, "Myosotis spp.");
assert.equal(runtime.find(x=>x.id===id)?.latin, "Myosotis spp.");
const photo={window:{}};vm.runInNewContext(read("js/ui/nature-flora-photographs.js"),photo);
const fallback=photo.window.HG_NATURE_FLORA_PHOTOS.get(id);
assert.equal(fallback?.scientificName,"Myosotis spp.");
assert.equal(fallback?.creator,"Zeynel Cebeci");
assert.equal(fallback?.license,"CC BY-SA 4.0");
assert.equal(fallback?.src,a.photoFallback);
const env={window:{}};vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env);
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert(approved.count >= 28,"Existing Myosotis approval must remain after later additions");
assert.equal(approved.get(id)?.scientificName,a.scientificName);
assert.equal(approved.get(id)?.taxonomicScope,"genus-representative");
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
const b=fs.readFileSync(new URL(a.src,root));
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");
assert.equal(b.toString("ascii",8,12),"WEBP");
assert.equal(b.toString("ascii",12,16),"VP8X");
assert((b[20]&0x10)!==0,"WebP must include transparent alpha");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],a.dimensions);
console.log("Forglemmegei: exact WebP, SHA256, Git SHA, alpha, genus caption, photo provenance and 28 approvals verified.");
