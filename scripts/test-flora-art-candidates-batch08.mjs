import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const r=JSON.parse(read("data/natur/flora/illustration-quality-batch08-20261030.json"));
assert.equal(r.batch,"08");
assert.equal(r.items.length,2);
const old=r.items.find(a=>a.key==="01_rodklover_v3");
const a=r.items.find(a=>a.key==="01_rodklover_v4");
assert(old&&a&&old.catalogId===a.catalogId);
assert.equal(old.reviewStatus,"needs_redraw");
assert.equal(old.botanicalVisualDecision,"failed_flower_morphology");
assert.equal(old.approvedForPublication,false);
assert(a.approvedForPublication && a.reviewStatus==="approved");
assert.equal(a.catalogId,"emne_flora_rodkløver");
assert.equal(a.scientificName,"Trifolium pratense");
assert(a.visualChecks.transparent&&a.visualChecks.blackBackgroundReviewed&&a.visualChecks.whiteBackgroundReviewed&&a.visualChecks.flowerMorphologyPassed);
assert(a.sourceReferences.length>=2&&a.limitations.length>100);
const s=JSON.parse(read("data/natur/flora/blomster.json"));
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
assert.equal(s.find(x=>x.id===a.catalogId)?.latin,a.scientificName);
assert.equal(runtime.find(x=>x.id===a.catalogId)?.latin,a.scientificName);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env);
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,16,"unexpected total approvals");
assert.equal(approved.get(a.catalogId)?.src,a.src,"v4 must be active");
assert.equal(approved.get(a.catalogId)?.gitBlobSha,a.gitBlobSha);
assert.notEqual(approved.get(a.catalogId)?.src,old.src,"v3 must remain rejected");
const photo={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-photographs.js"),photo);
assert.equal(photo.window.HG_NATURE_FLORA_PHOTOS.get(a.catalogId)?.scientificName,a.scientificName);
const previous=JSON.parse(read("data/natur/flora/illustration-quality-batch05-20261028.json")).items.find(x=>x.catalogId===a.catalogId);
assert(previous&&previous.approvedForPublication===false&&previous.src===a.historicalRejectedSrc);
for(const entry of [old,a]) {
 const b=fs.readFileSync(new URL(entry.src,root));
 assert.equal(b.length,entry.sizeBytes);
 assert.equal(crypto.createHash("sha256").update(b).digest("hex"),entry.sha256);
 assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),entry.gitBlobSha);
 assert.equal(b.toString("ascii",0,4),"RIFF");
 assert.equal(b.toString("ascii",8,12),"WEBP");
 assert.equal(b.toString("ascii",12,16),"VP8X");
 assert(b[20]&0x10,"missing extended WebP alpha channel");
 assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],entry.dimensions);
}
console.log("Finn Flora b08: 16 approvals; red clover v4 WebP, SHA, taxon, photo fallback OK; rejected v3 and b05 remain excluded");
