import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const r=JSON.parse(read("data/natur/flora/illustration-quality-batch08-20261030.json"));
assert.equal(r.batch,"08");
assert.equal(r.items.length,1);
const a=r.items[0];
assert.equal(a.catalogId,"emne_flora_rodkløver");
assert.equal(a.scientificName,"Trifolium pratense");
assert.equal(a.reviewStatus,"needs_redraw");
assert.equal(a.botanicalVisualDecision,"failed_flower_morphology");
assert.equal(a.approvedForPublication,false);
assert(a.requiredRedraw.length>=3 && a.sourceReferences.length>=2);
const s=JSON.parse(read("data/natur/flora/blomster.json"));
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
assert.equal(s.find(x=>x.id===a.catalogId)?.latin,a.scientificName);
assert.equal(runtime.find(x=>x.id===a.catalogId)?.latin,a.scientificName);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env);
assert.equal(env.window.HG_NATURE_FLORA_APPROVED.count,15,"candidate must not inflate approval count");
assert(!env.window.HG_NATURE_FLORA_APPROVED.has(a.catalogId),"rejected candidate must not become active");
const photo={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-photographs.js"),photo);
assert.equal(photo.window.HG_NATURE_FLORA_PHOTOS.get(a.catalogId)?.scientificName,a.scientificName);
const previous=JSON.parse(read("data/natur/flora/illustration-quality-batch05-20261028.json")).items.find(x=>x.catalogId===a.catalogId);
assert(previous && previous.approvedForPublication===false && previous.src===a.historicalRejectedSrc);
const b=fs.readFileSync(new URL(a.candidate,root));
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");
assert.equal(b.toString("ascii",8,12),"WEBP");
assert.equal(b.toString("ascii",12,16),"VP8X");
assert(b[20]&0x10,"missing extended WebP alpha channel");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],a.dimensions);
console.log("Finn Flora b08: exact WebP validated; red clover v3 correctly held pending flower redraw, 15 approvals unchanged");
