import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const review=JSON.parse(read("data/natur/flora/illustration-quality-svalerot-20261105.json")),a=review.items[0];
const id="emne_flora_svalerot",latin="Vincetoxicum hirundinaria",quiz="quiz_nature_flora_svalerot";
assert.equal(review.baselineApproved,82);
assert.equal(review.approvedCountAfterRelease,83);
assert.equal(review.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
const original=JSON.parse(read("data/natur/flora/blomster.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]).find(x=>x.id===id);
for(const x of [original,runtime]){
  assert(x,"Missing existing Svalerot record");
  assert.equal(x.title,"Svalerot");
  assert.equal(x.latin,latin);
  assert.equal(x.related_flora_id,"flora_svalerot");
  assert.equal(x.taxonomy?.latin_navn,latin);
  assert.equal(x.taxonomy?.familie,"Apocynaceae");
  assert(x.quiz_ids?.includes(quiz),"Existing quiz ID must remain");
  assert(x.kjennetegn?.some(t=>/hvite/.test(t)));
  assert(x.kjennetegn?.some(t=>/motsatte/.test(t)));
  assert(x.fenologi?.blomstring?.includes("juni"));
  assert(!JSON.stringify(x).includes("Lathraea squamaria"),"Skjellrot scientific name must not persist in Svalerot record");
  assert(!JSON.stringify(x.kjennetegn).includes("mangler grønne blader"),"Skjellrot morphology must not persist");
}
const data=fs.readFileSync(new URL(a.src,root));
assert.equal(data.length,a.sizeBytes);
assert.equal(data.length,426160);
assert.equal(crypto.createHash("sha256").update(data).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+data.length),Buffer.from([0]),data])).digest("hex"),a.gitBlobSha);
assert.equal(data.toString("ascii",0,4),"RIFF");
assert.equal(data.toString("ascii",8,12),"WEBP");
assert.equal(data.toString("ascii",12,16),"VP8X");
assert((data[20]&0x10)!==0,"WebP alpha required");
assert.deepEqual([1+data.readUIntLE(24,3),1+data.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed&&a.visualChecks.fullImageReviewed&&a.visualChecks.botanicalApproved);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,83);
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_rosslyng")?.src);
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_rodtvetann")?.src);
console.log("Svalerot #83: morphology, corrected taxonomy, quiz ID, transparent WebP hash, and 83 approved validated.");
