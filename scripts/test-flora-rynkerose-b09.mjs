import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/flora/illustration-quality-rynkerose-20261106.json")),a=q.items[0];
const id="emne_flora_rynkerose",latin="Rosa rugosa",quiz="quiz_nature_flora_rynkerose";
assert.equal(q.baselineApproved,83);
assert.equal(q.approvedCountAfterRelease,84);
assert.equal(q.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"b66382b7a76f60773eef79ad46b3ecb425c41b9b");
assert.equal(a.sha256,"ee75c09d3ac6a95dd9d261bf5ea2c4e398adc6102f3fc42ce23e158087d19cfd");
const native=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]).find(x=>x.id===id);
for(const x of [native,runtime]){
 assert(x,"Missing Rynkerose record");
 assert.equal(x.title,"Rynkerose");
 assert.equal(x.latin,latin);
 assert.equal(x.taxonomy?.latin_navn,latin);
 assert.equal(x.taxonomy?.familie,"Rosaceae");
 assert.equal(x.related_flora_id,"flora_rynkerose");
 assert.equal(x.status?.type,"fremmed_art");
 assert(x.quiz_ids?.includes(quiz));
 assert(x.kjennetegn?.some(x=>/rynke/.test(x)));
 assert(x.kjennetegn?.some(x=>/nyper/.test(x)));
}
const bin=fs.readFileSync(new URL(a.src,root));
assert.equal(bin.length,604712);
assert.equal(bin.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(bin).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bin.length),Buffer.from([0]),bin])).digest("hex"),a.gitBlobSha);
assert.equal(bin.toString("ascii",0,4),"RIFF");
assert.equal(bin.toString("ascii",8,12),"WEBP");
assert.equal(bin.toString("ascii",12,16),"VP8X");
assert((bin[20]&0x10)!==0,"WebP with alpha required");
assert.deepEqual([1+bin.readUIntLE(24,3),1+bin.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.transparent&&a.visualChecks.blackBackgroundReviewed&&a.visualChecks.fullImageReviewed&&a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert(approved.count>=84,"The 84 previously approved species must remain approved");
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_flora_svalerot")?.scientificName,"Vincetoxicum hirundinaria");
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_svalerot")?.src);
assert.equal(approved.get("emne_flora_knoppurt")?.src,approved.get("emne_flora_engknoppurt")?.src);
console.log("Rynkerose #84: species and quiz preserved, exact transparent WebP, and 84 approved registered.");
