import assert from "node:assert/strict";import fs from "node:fs";import crypto from "node:crypto";import vm from "node:vm";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
const entry=JSON.parse(read("data/natur/flora/illustration-quality-bergmynte-20261031.json")).items[0],id="emne_flora_bergmynte";
const ctx={window:{}};vm.runInNewContext(read("js/ui/nature-flora-approved.js"),ctx);
assert(ctx.window.HG_NATURE_FLORA_APPROVED.count >= 22);
assert.equal(ctx.window.HG_NATURE_FLORA_APPROVED.get(id)?.src,entry.src);
const source=JSON.parse(read("data/natur/flora/blomster.json"));
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
assert.equal(source.find(x=>x.id===id)?.latin,"Origanum vulgare");
assert.equal(runtime.find(x=>x.id===id)?.latin,"Origanum vulgare");
const photos={window:{}};vm.runInNewContext(read("js/ui/nature-flora-photographs.js"),photos);
assert.equal(photos.window.HG_NATURE_FLORA_PHOTOS.get(id)?.scientificName,"Origanum vulgare");
assert(entry.reviewStatus==="approved"&&entry.approvedForPublication&&entry.sourceReferences.length>=2);
const b=fs.readFileSync(new URL("../"+entry.src,import.meta.url));
assert.equal(b.length,entry.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),entry.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),entry.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");assert.equal(b.toString("ascii",8,12),"WEBP");assert.equal(b.toString("ascii",12,16),"VP8X");
assert(b[20]&0x10);assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],entry.dimensions);
console.log("Bergmynte: 22 approved, verified WebP hash/alpha, canonical taxon and licensed photo fallback");
