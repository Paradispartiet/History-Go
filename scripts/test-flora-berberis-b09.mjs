import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/flora/illustration-quality-berberis-20261110.json")),a=q.items[0];
const id="emne_flora_berberis",latin="Berberis spp.",quiz="quiz_nature_flora_berberis";
assert.equal(q.baselineApproved,93);
assert.equal(q.approvedCountAfterRelease,94);
assert.equal(q.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"57d1070b052ec5b1f6c30650f47a688a93d14039");
assert.equal(a.sha256,"20ed141df4e096ba46e0c25d28968ce2932a977b9403317ecd8bd875a2b4a1a2");
const source=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]).find(x=>x.id===id);
const kratt=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]).find(x=>x.id==="emne_kratt_berberis");
for(const x of [source,runtime]){
 assert(x,"Berberis source/runtime entry missing");
 assert.equal(x.title,"Berberis");
 assert.equal(x.latin,latin);
 assert.equal(x.taxonomy?.latin_navn,latin);
 assert.equal(x.taxonomy?.familie,"Berberidaceae");
 assert.equal(x.related_flora_id,"flora_berberis");
 assert.equal(x.status?.type,"fremmed_art");
 assert(x.quiz_ids?.includes(quiz));
 assert(x.kjennetegn?.some(t=>t.includes("tornete")));
 assert(x.kjennetegn?.some(t=>t.includes("gule")));
 assert(x.kjennetegn?.some(t=>t.includes("bær")));
}
assert(kratt && kratt.quiz_ids?.includes("quiz_kratt_berberis"));
const host=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id==="emne_flora_hostberberis");
assert(host && host.latin==="Berberis thunbergii","Separate Høstberberis entry required");
const bytes=fs.readFileSync(new URL(a.src,root));
assert.equal(bytes.length,641248);
assert.equal(bytes.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bytes.length),Buffer.from([0]),bytes])).digest("hex"),a.gitBlobSha);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.equal(bytes.toString("ascii",12,16),"VP8X");
assert((bytes[20]&0x10)!==0,"Transparent WebP alpha required");
assert.deepEqual([1+bytes.readUIntLE(24,3),1+bytes.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed&&a.visualChecks.fullImageReviewed&&a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,94);
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_kratt_berberis")?.gitBlobSha,a.gitBlobSha,"Kratt-Berberis must reuse the one genus image");
assert.equal(approved.get("emne_kratt_berberis")?.src,a.src,"Both Berberis cards must share one image");
assert(!approved.get("emne_flora_hostberberis")||approved.get("emne_flora_hostberberis")?.src!==a.src,"Høstberberis must not be incorrectly identified with Berberis genus representative");
assert.equal(approved.get("emne_flora_mahonia")?.scientificName,"Mahonia aquifolium");
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_mahonia")?.src);
console.log("Berberis #94: genus illustration, original WebP, both card IDs, hashes, separate Høstberberis and 94 approved entries verified.");
