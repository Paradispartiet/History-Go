import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/flora/illustration-quality-aakersvineblom-20261111.json")),a=q.items[0];
const id="emne_flora_aakersvineblom",latin="Senecio vulgaris",quiz="quiz_nature_flora_aakersvineblom";
assert.equal(q.baselineApproved,107);
assert.equal(q.approvedCountAfterRelease,108);
assert.equal(q.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"cb143fd0f24c23410b51f3d5e66c367855762c23");
assert.equal(a.sha256,"1d9aa9e16e20e1dde8007e2758301c246458a4bc09129478b6ecdc6d0087e43d");
const source=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const flora=runtime.find(x=>x.id===id);
for(const x of [source,flora]){
 assert(x,"Åkersvineblom source/runtime record missing");
 assert.equal(x.title,"Åkersvineblom");
 assert.equal(x.latin,latin);
 assert.equal(x.taxonomy?.latin_navn,latin);
 assert.equal(x.taxonomy?.familie,"Asteraceae");
 assert.equal(x.related_flora_id,"flora_aakersvineblom");
 assert(x.quiz_ids?.includes(quiz));
}
assert(!runtime.find(x=>x.id==="emne_ved_aakersvineblom"),"Do not invent a ved card for this herb");
const b=fs.readFileSync(new URL(a.src,root));
assert.equal(b.length,195010);
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");
assert.equal(b.toString("ascii",8,12),"WEBP");
assert.equal(b.toString("ascii",12,16),"VP8X");
assert((b[20]&0x10)!==0,"Transparent WebP alpha required");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed && a.visualChecks.fullImageReviewed && a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
assert(a.observations.length>100);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,108);
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_ved_aakersvineblom"),null);
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_sitkagran")?.src);
console.log("Åkersvineblom #108: species record, unchanged quiz, transparent WebP, hashes and 108 originals verified.");
