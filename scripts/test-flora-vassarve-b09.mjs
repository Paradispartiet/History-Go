import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";

const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const doc=JSON.parse(read("data/natur/flora/illustration-quality-vassarve-20261103.json"));
const a=doc.items[0];
assert.equal(doc.baselineApproved,67);
assert.equal(doc.approvedCountAfterRelease,68);
assert.equal(a.catalogId,"emne_flora_vassarve");
assert.equal(a.scientificName,"Stellaria media");
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
const canonical=JSON.parse(read("data/natur/flora/blomster.json")).find(z=>z.id===a.catalogId);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(z=>z.kind==="emne_pack"?z.items:[z]).find(z=>z.id===a.catalogId);
for(const x of [canonical,runtime]){
 assert(x,"Missing original Vassarve species");
 assert.equal(x.title,"Vassarve");
 assert.equal(x.latin,"Stellaria media");
 assert(x.quiz_ids?.includes("quiz_nature_flora_vassarve"),"Existing quiz ID must remain");
}
const data=fs.readFileSync(new URL(a.src,root));
assert.equal(data.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(data).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+data.length),Buffer.from([0]),data])).digest("hex"),a.gitBlobSha);
assert.equal(data.toString("ascii",0,4),"RIFF");
assert.equal(data.toString("ascii",8,12),"WEBP");
assert.equal(data.toString("ascii",12,16),"VP8X");
assert((data[20]&0x10)!==0,"Original alpha required");
assert.deepEqual([1+data.readUIntLE(24,3),1+data.readUIntLE(27,3)],[1024,1536]);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert(approved.count >= 68, "At least the 68 previously approved illustrations must remain");
assert.equal(approved.get(a.catalogId)?.src,a.src);
assert.equal(approved.get(a.catalogId)?.gitBlobSha,a.gitBlobSha);
assert.notEqual(approved.get(a.catalogId)?.src,approved.get("emne_flora_tyskhonsetarm")?.src);
console.log("Vassarve #68: 1024x1536 alpha WebP, exact Git SHA, botanical catalog and quiz unchanged.");
