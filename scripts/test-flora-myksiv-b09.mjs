import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/flora/illustration-quality-myksiv-20261112.json")),a=q.items[0];
const id="emne_flora_myksiv",latin="Juncus effusus",quiz="quiz_nature_flora_myksiv";
assert.equal(q.baselineApproved,116);
assert.equal(q.approvedCountAfterRelease,117);
assert.equal(q.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"0aaa462e4cd5923a29c8c903521abe76f3169a1d");
assert.equal(a.sha256,"68b4895f76506012e90fcd82a355346b59d613b13305d170af8fadb48f929343");
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const flora=runtime.find(x=>x.id===id);
assert(flora,"Original Myksiv runtime record missing");
assert.equal(flora.title,"Myksiv");
assert.equal(flora.latin,latin);
assert.equal(flora.taxonomy?.norsk_navn,"Myksiv");
assert.equal(flora.taxonomy?.latin_navn,latin);
assert.equal(flora.taxonomy?.familie,"Juncaceae");
assert.equal(flora.related_flora_id,"flora_myksiv");
assert.deepEqual(Array.from(flora.quiz_ids),[quiz],"Original quiz ID must remain unchanged");
const similar=runtime.filter(x=>x.id!=="emne_flora_myksiv" && x.latin===latin);
assert(similar.some(x=>x.id==="emne_siv_vassiv"),"Existing Vassiv card must remain");
assert(similar.some(x=>x.id==="emne_siv_fellesiv"),"Existing Fellesiv card must remain");
const b=fs.readFileSync(new URL(a.src,root));
assert.equal(b.length,358988);
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");
assert.equal(b.toString("ascii",8,12),"WEBP");
assert.equal(b.toString("ascii",12,16),"VP8X");
assert((b[20]&0x10)!==0,"True WebP alpha is required");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed && a.visualChecks.fullImageReviewed && a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
assert(a.observations.length>100);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,117);
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_flora_rynkesurbaer")?.gitBlobSha,"3059a859aea76264001162d81a29e5257192aa12","Original #116 must stay unchanged");
assert.equal(approved.get("emne_siv_vassiv"),null,"Vassiv is a distinct card, do not redirect it");
assert.equal(approved.get("emne_siv_fellesiv"),null,"Fellesiv is a distinct card, do not redirect it");
console.log("Myksiv #117: correct runtime species, unchanged quiz, transparent WebP, and 117 original illustrations verified.");
