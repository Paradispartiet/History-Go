import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
const read=path=>fs.readFileSync(new URL("../"+path,import.meta.url),"utf8");
const readBytes=path=>fs.readFileSync(new URL("../"+path,import.meta.url));
const manifest=JSON.parse(read("data/natur/flora/illustration-candidates-batch02.json"));
assert.equal(manifest.batch,"02");
assert.equal(manifest.items.length,2);
const catalog=JSON.parse(read("data/runtime/nature-all/flora-001.json"))
  .flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const used=new Set();
for(const p of manifest.items){
 assert.equal(p.approvedForPublication,false,"a candidate cannot override an artsfoto");
 assert.equal(p.transparent,true);
 assert(["needs_species_review","needs_redraw"].includes(p.reviewStatus));
 assert(p.issues.length>=24,"missing botanical quality finding");
 assert(p.botanicalReferenceUrl.startsWith("https://"),"missing botanical reference");
 assert(!used.has(p.catalogId),"duplicate species");used.add(p.catalogId);
 const entry=catalog.find(c=>c.id===p.catalogId);
 assert(entry,"unknown catalog id: "+p.catalogId);
 assert.equal(entry.latin,p.scientificName);
 assert.match(p.src,/^bilder\/natur\/flora\/illustrasjonskandidater\/b02\/\d{2}_[a-z]+(?:_v\d+)?\.webp$/);
 const bin=readBytes(p.src);
 assert(bin.length>20000 && bin.length<800000,"unexpected image size");
 assert.equal(bin.toString("ascii",0,4),"RIFF","not a RIFF image");
 assert.equal(bin.toString("ascii",8,12),"WEBP","not WebP");
 assert.equal(bin.toString("ascii",12,16),"VP8X","not extended WebP");
 assert((bin[20]&0x10)!==0,"image missing alpha channel");
 const sha=crypto.createHash("sha1")
  .update(Buffer.concat([Buffer.from("blob "+bin.length+"\0"),bin])).digest("hex");
 assert.equal(sha,p.gitBlobSha,"file changed after reviewed upload");
 const gallery=read("flora-illustrasjoner-bolk02.html");
 assert(gallery.includes(p.src),"missing image on review gallery");
 assert(gallery.includes(p.issues),"missing QA finding on gallery");
}
const ball=manifest.items.find(p=>p.catalogId==="emne_flora_ballblom");
assert.equal(ball?.reviewStatus,"needs_species_review","redrawn globeflower is still unapproved");
assert.equal(ball?.previousSrc,"bilder/natur/flora/illustrasjonskandidater/b02/01_ballblom.webp");
assert.equal(ball?.previousGitBlobSha,"aa6a051e28c9299513a3660d7589931b3cc3a903");
assert.notEqual(ball.gitBlobSha,ball.previousGitBlobSha);
assert(ball.reviewEvidenceUrls?.length>=2,"globeflower reference comparison missing");
assert(ball.issues.includes("kuleformede")&&ball.issues.includes("bladverket"),"globeflower morphology notes missing");
const oldBall=readBytes(ball.previousSrc);
const oldGit=crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+oldBall.length+"\0"),oldBall])).digest("hex");
assert.equal(oldGit,ball.previousGitBlobSha,"before version missing or modified");
const eng=manifest.items.find(p=>p.catalogId==="emne_flora_engkarse");
assert.equal(eng?.reviewStatus,"needs_species_review","redrawn engkarse must remain unapproved");
assert.equal(eng?.previousSrc,"bilder/natur/flora/illustrasjonskandidater/b02/02_engkarse.webp");
assert.equal(eng?.previousGitBlobSha,"f67f79670dd23783a42f79551635ff5dc96dcab5");
assert.notEqual(eng.gitBlobSha,eng.previousGitBlobSha);
assert(eng.issues.includes("avrundede")&&eng.issues.includes("ugreinete"),"engkarse morphology and limitations missing");
assert(eng.reviewEvidenceUrls?.length>=2&&eng.botanicalReferenceUrl.includes("kew.org"),"engkarse evidence missing");
const oldEng=readBytes(eng.previousSrc);
const oldEngSha=crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+oldEng.length+"\0"),oldEng])).digest("hex");
assert.equal(oldEngSha,eng.previousGitBlobSha,"old engkarse version changed");
assert(read("flora-illustrasjoner-bolk02.html").includes(eng.previousSrc),"engkarse before/after gallery missing");
assert(!manifest.items.some(p=>p.approvedForPublication),"unreviewed drawings cannot be published");
const js=read("js/ui/flora-illustration-review.js");
assert(js.includes('["01","02","03","04"]'),"all candidate batches must be loaded in the review gallery");
assert(js.includes('illustration-candidates-batch"+batch+".json"'),"shared candidate manifest loader missing");
assert(js.includes('candidate.approvedForPublication===false'),"review gate disabled");
const explorer=read("js/ui/nature-explorer.js");
const app=read("finn-flora.html");
assert(explorer.includes('window.HG_NATURE_FLORA_APPROVED'), 'flora publication requires explicit approved-image registry');
assert(!app.includes("illustrasjonskandidater/b02/"),"candidate leaked into app");
console.log("Flora candidate batch 02: 2 alpha WebP assets, botanical QA flags and photo-only production gate valid.");
