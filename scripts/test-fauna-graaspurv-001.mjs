import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/fauna/illustration-quality-graaspurv-20261112.json"));
const a=q.items[0],id="emne_fauna_graaspurv",latin="Passer domesticus";
assert.equal(q.speciesNumber,1);assert.equal(q.approvedCountAfterRelease,1);
assert.equal(q.items.length,1);assert.equal(a.catalogId,id);assert.equal(a.scientificName,latin);
assert.equal(a.family,"Passeridae");assert.equal(a.existingQuizId,"quiz_fauna_graaspurv");
assert.equal(a.reviewStatus,"approved");assert.equal(a.approvedForPublication,true);assert.equal(a.originalBinaryVerified,true);
assert.equal(a.gitBlobSha,"468b3c17af9a0b90aebe7ce1cdd6866f9224687f");assert.equal(a.sha256,"25936141b096a16689ab0441c32d545caaf4617121e2b1ba9e7766fa6df1ed83");
assert(a.sourceReferences.length>=2);assert(a.visualChecks.blackBackgroundReviewed);assert(a.visualChecks.maleAndFemaleSexualDimorphism);
const source=JSON.parse(read("data/natur/fauna/fugler_by.json")).find(x=>x.id===id);
const chunks=JSON.parse(read("data/runtime/nature-all/fauna-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const rt=chunks.find(x=>x.id===id);
assert(source&&rt,"Existing original bird records must be present");
for(const v of [source,rt]) {assert.equal(v.title,"Gråspurv");assert.equal(v.latin,latin);assert.equal(v.taxonomy?.latin_navn,latin);assert.equal(v.taxonomy?.familie,"Passeridae");assert(v.quiz_ids?.includes("quiz_fauna_graaspurv"));}
const b=fs.readFileSync(new URL(a.src,root));
assert.equal(b.length,a.sizeBytes);assert.equal(b.length,355924);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");assert.equal(b.toString("ascii",8,12),"WEBP");assert.equal(b.toString("ascii",12,16),"VP8X");assert((b[20]&0x10)!==0);
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],[1024,1536]);
const env={window:{}};vm.runInNewContext(read("js/ui/nature-fauna-approved.js"),env);
const approved=env.window.HG_NATURE_FAUNA_APPROVED;
assert.equal(approved.count,1);assert.equal(approved.get(id)?.src,a.src);assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);assert.equal(approved.get("emne_fauna_kraake"),null);
const explorer=read("js/ui/nature-explorer.js"),html=read("finn-fauna.html");
assert(explorer.includes("approvedFaunaIllustrations?.get(id)?.src"),"Approved originals must take priority over schematic SVG");
assert(explorer.includes("const art=drawings?.resolve(id);"),"Old SVG fallback must stay");
assert(html.includes("js/ui/nature-fauna-approved.js"),"The registry must load before the explorer");
const old=read("scripts/test-nature-illustrations.mjs");assert(old.includes("330"),"The 330 earlier schematic illustrations must remain covered");
console.log("Finn Fauna #1 Gråspurv: WebP original, male/female, original species/quiz and legacy fallback verified.");
