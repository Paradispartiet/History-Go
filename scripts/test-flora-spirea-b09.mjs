import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/flora/illustration-quality-spirea-20261110.json")),a=q.items[0];
const id="emne_flora_spirea",latin="Spiraea spp.",quiz="quiz_nature_flora_spirea";
assert.equal(q.baselineApproved,94);
assert.equal(q.approvedCountAfterRelease,95);
assert.equal(q.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"252c311109bcd3beb0535b242dba234d7ce6f811");
assert.equal(a.sha256,"ece568085aedd4113b40db569b78f7f55f1940284e0534d1d2a8b8723f51f569");
const source=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const flora=runtime.find(x=>x.id===id);
const kratt=runtime.find(x=>x.id==="emne_kratt_spirea");
for(const x of [source,flora]){
 assert(x,"Spirea source/runtime entry missing");
 assert.equal(x.title,"Spirea");
 assert.equal(x.latin,latin);
 assert.equal(x.taxonomy?.latin_navn,latin);
 assert.equal(x.taxonomy?.familie,"Rosaceae");
 assert.equal(x.related_flora_id,"flora_spirea");
 assert.equal(x.status?.type,"fremmed_art");
 assert(x.quiz_ids?.includes(quiz));
 assert(x.kjennetegn?.some(t=>t.includes("hvite/rosa")));
}
assert(kratt && kratt.quiz_ids?.includes("quiz_kratt_spirea"));
assert.equal(kratt.latin,latin);
const bytes=fs.readFileSync(new URL(a.src,root));
assert.equal(bytes.length,597610);
assert.equal(bytes.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bytes.length),Buffer.from([0]),bytes])).digest("hex"),a.gitBlobSha);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.equal(bytes.toString("ascii",12,16),"VP8X");
assert((bytes[20]&0x10)!==0,"Transparent WebP alpha required");
assert.deepEqual([1+bytes.readUIntLE(24,3),1+bytes.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed&&a.visualChecks.fullImageReviewed&&a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert(approved.count>=95,"Previous 95 originals must remain approved");
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_kratt_spirea")?.src,a.src);
assert.equal(approved.get("emne_kratt_spirea")?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_flora_berberis")?.scientificName,"Berberis spp.");
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_berberis")?.src);
console.log("Spirea #95: genus artwork, transparent WebP, both cards, Git hashes, IDs and 95 approved originals verified.");
