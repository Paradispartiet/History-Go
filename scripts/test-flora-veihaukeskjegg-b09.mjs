import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const review=JSON.parse(read("data/natur/flora/illustration-quality-veihaukeskjegg-20261103.json"));
const a=review.items[0];
assert.equal(review.baselineApproved,68);
assert.equal(review.approvedCountAfterRelease,69);
assert.equal(a.catalogId,"emne_flora_veihaukeskjegg");
assert.equal(a.scientificName,"Crepis tectorum");
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
for(const path of ["data/natur/flora/blomster.json","data/runtime/nature-all/flora-001.json"]){
 const xs=JSON.parse(read(path)).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
 const x=xs.find(x=>x.id===a.catalogId);
 assert(x,"Missing original species");
 assert.equal(x.title,a.name);
 assert.equal(x.latin,a.scientificName);
 assert(x.quiz_ids?.includes(a.existingQuizId));
}
const data=fs.readFileSync(new URL(a.src,root));
assert.equal(data.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(data).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+data.length),Buffer.from([0]),data])).digest("hex"),a.gitBlobSha);
assert.equal(data.toString("ascii",0,4),"RIFF");
assert.equal(data.toString("ascii",8,12),"WEBP");
assert.equal(data.toString("ascii",12,16),"VP8X");
assert((data[20]&0x10)!==0,"Original alpha required");
assert.deepEqual([1+data.readUIntLE(24,3),1+data.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed && a.visualChecks.originalAlphaVerified);
assert(a.sourceReferences.length>=2 && a.observations.length>100);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,69);
assert.equal(approved.get(a.catalogId)?.src,a.src);
assert.equal(approved.get(a.catalogId)?.scientificName,a.scientificName);
assert.equal(approved.get(a.catalogId)?.gitBlobSha,a.gitBlobSha);
console.log("Veihaukeskjegg #69: exact WebP Git SHA and alpha, botanical catalog and approved registry verified.");
