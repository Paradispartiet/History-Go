import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
const file=p=>fs.readFileSync(new URL("../"+p,import.meta.url));
const m=JSON.parse(read("data/natur/flora/illustration-candidates-batch03.json"));
assert.equal(m.schema,"history-go-flora-art-candidates-v1");
assert.equal(m.batch,"03");
assert.equal(m.items.length,1);
const p=m.items[0];
assert.equal(p.catalogId,"emne_flora_hestehov");
assert.equal(p.scientificName,"Tussilago farfara");
assert.equal(p.season,"spring");
assert.equal(p.transparent,true);
assert.equal(p.reviewStatus,"needs_species_review");
assert.equal(p.approvedForPublication,false);
assert(p.qualityNotes.includes("skjellkledde")&&p.missingStage.includes("etter blomstring"));
assert(p.botanicalReferenceUrls.length>=2);
const catalog=JSON.parse(read("data/runtime/nature-all/flora-001.json"))
 .flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
assert.equal(catalog.find(x=>x.id===p.catalogId)?.latin,p.scientificName);
assert.match(p.src,/^bilder\/natur\/flora\/illustrasjonskandidater\/b03\/01_hestehov_var\.webp$/);
const bytes=file(p.src);
assert(bytes.length>20000&&bytes.length<700000);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.equal(bytes.toString("ascii",12,16),"VP8X");
assert((bytes[20]&0x10)!==0,"transparent alpha channel required");
const sha=crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bytes.length+"\0"),bytes])).digest("hex");
assert.equal(sha,p.gitBlobSha);
const gallery=read("flora-illustrasjoner-bolk03.html");
assert(gallery.includes(p.src)&&gallery.includes("Etter blomstring"));
assert(gallery.includes("godkjent for Finn Flora"));
const review=read("js/ui/flora-illustration-review.js");
assert(review.includes('["01","02","03","04","05"]'));
assert(review.includes("candidate.approvedForPublication===false"));
assert(read("flora-illustration-review.html").includes("flora-illustrasjoner-bolk03.html"));
const app=read("finn-flora.html"),explorer=read("js/ui/nature-explorer.js");
assert(!app.includes("illustrasjonskandidater/b03")&&!explorer.includes("illustrasjonskandidater/b03"));
assert(explorer.includes('window.HG_NATURE_FLORA_APPROVED'), 'flora publication requires explicit approved-image registry');
assert(read(".github/workflows/nature-illustrations.yml").includes("node scripts/test-flora-art-candidates-batch03.mjs"));
console.log("Flora hestehov batch 03: transparent WebP and spring morphology; zero publication approvals.");
