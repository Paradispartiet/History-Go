import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const quality=JSON.parse(read("data/natur/flora/illustration-quality-rosslyng-20261105.json")), item=quality.items[0];
const id="emne_flora_rosslyng", latin="Calluna vulgaris", quiz="quiz_nature_flora_rosslyng";
assert.equal(quality.baselineApproved,81);
assert.equal(quality.approvedCountAfterRelease,82);
assert.equal(quality.items.length,1);
assert.equal(item.catalogId,id);
assert.equal(item.scientificName,latin);
assert.equal(item.existingQuizId,quiz);
assert.equal(item.reviewStatus,"approved");
assert.equal(item.approvedForPublication,true);
const original=JSON.parse(read("data/natur/flora/blomster.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]).find(x=>x.id===id);
for(const x of [original,runtime]){
 assert(x,"Missing existing Røsslyng record");
 assert.equal(x.title,"Røsslyng");
 assert.equal(x.latin,latin);
 assert.equal(x.taxonomy?.latin_navn,latin);
 assert.equal(x.taxonomy?.familie,"Ericaceae");
 assert(x.quiz_ids?.includes(quiz),"Existing quiz ID must remain");
}
const bin=fs.readFileSync(new URL(item.src,root));
assert.equal(bin.length,577054);
assert.equal(bin.length,item.sizeBytes);
assert.equal(crypto.createHash("sha256").update(bin).digest("hex"),item.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bin.length),Buffer.from([0]),bin])).digest("hex"),item.gitBlobSha);
assert.equal(bin.toString("ascii",0,4),"RIFF");
assert.equal(bin.toString("ascii",8,12),"WEBP");
assert.equal(bin.toString("ascii",12,16),"VP8X");
assert((bin[20]&0x10)!==0,"WebP alpha required");
assert.deepEqual([1+bin.readUIntLE(24,3),1+bin.readUIntLE(27,3)],[1024,1536]);
assert(item.visualChecks.transparent&&item.visualChecks.blackBackgroundReviewed&&item.visualChecks.fullImageReviewed&&item.visualChecks.botanicalApproved);
assert(item.sourceReferences.length>=2);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert(approved.count>=82,"Røsslyng #82 must remain approved after later releases");
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,item.src);
assert.equal(approved.get(id)?.gitBlobSha,item.gitBlobSha);
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_rodtvetann")?.src);
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_engknoppurt")?.src);
console.log("Røsslyng #82: species IDs, transparent WebP, hashes and 82 approved validated.");
