import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const qa=JSON.parse(read("data/natur/flora/illustration-quality-syrin-20261110.json")), a=qa.items[0];
const id="emne_flora_syrin", latin="Syringa vulgaris", quiz="quiz_nature_flora_syrin";
assert.equal(qa.baselineApproved,96);
assert.equal(qa.approvedCountAfterRelease,97);
assert.equal(qa.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"8a0f0d616ae6f5c546a1366fdb049468c9128c89");
assert.equal(a.sha256,"e9d56b97735d3fa1b3cd593a369b50d9d20bf7988e336b9ca0ac5bf98245ff23");
const source=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id===id);
const all=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const runtime=all.find(x=>x.id===id), kratt=all.find(x=>x.id==="emne_kratt_syrin");
for(const x of [source,runtime]){
 assert(x,"Syrin source/runtime entry missing");
 assert.equal(x.title,"Syrin");
 assert.equal(x.latin,latin);
 assert.equal(x.taxonomy?.latin_navn,latin);
 assert.equal(x.taxonomy?.familie,"Oleaceae");
 assert.equal(x.related_flora_id,"flora_syrin");
 assert.equal(x.status?.type,"fremmed_art");
 assert(x.quiz_ids?.includes(quiz));
 assert(x.kjennetegn?.some(t=>t.includes("duft")));
 assert(x.kjennetegn?.some(t=>t.includes("blomsterklaser")));
}
assert(kratt && kratt.latin===latin && kratt.quiz_ids?.includes("quiz_kratt_syrin"));
const bytes=fs.readFileSync(new URL(a.src,root));
assert.equal(bytes.length,660164);
assert.equal(bytes.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bytes.length),Buffer.from([0]),bytes])).digest("hex"),a.gitBlobSha);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.equal(bytes.toString("ascii",12,16),"VP8X");
assert((bytes[20]&0x10)!==0,"Transparent WebP alpha required");
assert.deepEqual([1+bytes.readUIntLE(24,3),1+bytes.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed&&a.visualChecks.fullImageReviewed&&a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,97);
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_kratt_syrin")?.src,a.src,"Both Syrin cards share original");
assert.equal(approved.get("emne_kratt_syrin")?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_flora_mispel")?.scientificName,"Cotoneaster spp.");
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_mispel")?.src);
console.log("Syrin #97: taxonomy, quiz, flora and kratt cards, WebP alpha, Git hash, and 97 approved images verified.");
