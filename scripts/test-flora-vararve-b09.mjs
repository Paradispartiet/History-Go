import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const review=JSON.parse(read("data/natur/flora/illustration-quality-vararve-20261104.json"));
const a=review.items[0];
assert.equal(review.baselineApproved,70);
assert.equal(review.approvedCountAfterRelease,71);
assert.equal(a.catalogId,"emne_flora_vararve");
assert.equal(a.scientificName,"Draba verna");
assert.equal(a.existingQuizId,"quiz_nature_flora_vararve");
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
for(const path of ["data/natur/flora/blomster.json","data/runtime/nature-all/flora-001.json"]){
 const xs=JSON.parse(read(path)).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
 const x=xs.find(x=>x.id===a.catalogId);
 assert(x,"Missing original species: "+path);
 assert.equal(x.title,a.name);
 assert.equal(x.latin,a.scientificName);
 assert(x.quiz_ids?.includes(a.existingQuizId));
}
const b=fs.readFileSync(new URL(a.src,root));
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");
assert.equal(b.toString("ascii",8,12),"WEBP");
assert.equal(b.toString("ascii",12,16),"VP8X");
assert((b[20]&0x10)!==0,"Original alpha required");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed && a.visualChecks.originalAlphaVerified);
assert(a.sourceReferences.length>=2 && a.observations.length>100);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,71);
assert.equal(approved.get(a.catalogId)?.src,a.src);
assert.equal(approved.get(a.catalogId)?.scientificName,a.scientificName);
assert.equal(approved.get(a.catalogId)?.gitBlobSha,a.gitBlobSha);
assert.notEqual(approved.get(a.catalogId)?.src,approved.get("emne_flora_villkarse")?.src);
console.log("Vårarve #71: botanical catalog and quiz unchanged, exact transparent WebP verified.");
