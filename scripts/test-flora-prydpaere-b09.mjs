import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),"utf8");
const q=JSON.parse(read("data/natur/flora/illustration-quality-prydpaere-20261110.json")),a=q.items[0];
const id="emne_flora_prydpaere",latin="Pyrus calleryana",quiz="quiz_nature_flora_prydpaere";
assert.equal(q.baselineApproved,103);
assert.equal(q.approvedCountAfterRelease,104);
assert.equal(q.items.length,1);
assert.equal(a.catalogId,id);
assert.equal(a.scientificName,latin);
assert.equal(a.existingQuizId,quiz);
assert.equal(a.reviewStatus,"approved");
assert.equal(a.approvedForPublication,true);
assert.equal(a.gitBlobSha,"b83fdaa1c76f1741fdd0395983cf100631ee9eb6");
assert.equal(a.sha256,"74be4133c52b7cfc07875eeb611a3539ad9c8d12f06c50b28344f5a869655cd9");
const src=JSON.parse(read("data/natur/flora/fremmedarter.json")).find(x=>x.id===id);
const runtime=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const flora=runtime.find(x=>x.id===id),ved=runtime.find(x=>x.id==="emne_ved_prydpaere");
for(const x of [src,flora]){
 assert(x,"Prydpære source/runtime record missing");
 assert.equal(x.title,"Prydpære");
 assert.equal(x.latin,"Pyrus calleryana");
 assert.equal(x.taxonomy?.latin_navn,"Pyrus calleryana");
 assert.equal(x.taxonomy?.familie,"Rosaceae");
 assert.equal(x.related_flora_id,"flora_prydpaere");
 assert(x.quiz_ids?.includes(quiz));
}
assert(ved && ved.quiz_ids?.includes("quiz_ved_prydpaere"));
assert.equal(ved.latin,"Pyrus calleryana");
const b=fs.readFileSync(new URL(a.src,root));
assert.equal(b.length,332938);
assert.equal(b.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(b).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length),Buffer.from([0]),b])).digest("hex"),a.gitBlobSha);
assert.equal(b.toString("ascii",0,4),"RIFF");
assert.equal(b.toString("ascii",8,12),"WEBP");
assert.equal(b.toString("ascii",12,16),"VP8X");
assert((b[20]&0x10)!==0,"Transparent WebP alpha required");
assert.deepEqual([1+b.readUIntLE(24,3),1+b.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed && a.visualChecks.fullImageReviewed && a.visualChecks.botanicalApproved);
assert(a.sourceReferences.length>=2);
assert(a.observations.length>100);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,104);
assert.equal(approved.get(id)?.scientificName,latin);
assert.equal(approved.get(id)?.src,a.src);
assert.equal(approved.get(id)?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_ved_prydpaere")?.src,a.src);
assert.equal(approved.get("emne_ved_prydpaere")?.gitBlobSha,a.gitBlobSha);
assert.equal(approved.get("emne_flora_prydkirsebaer")?.scientificName,"Prunus serrulata (m.fl.)");
assert.notEqual(approved.get(id)?.src,approved.get("emne_flora_prydkirsebaer")?.src);
console.log("Prydpære #104: group taxon, two cards, WebP alpha, hashes and 104 originals verified.");
