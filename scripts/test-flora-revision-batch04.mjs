import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import crypto from "node:crypto";

const read = path=>fs.readFileSync(new URL("../"+path,import.meta.url),"utf8");
const bytes = path=>fs.readFileSync(new URL("../"+path,import.meta.url));
const data=JSON.parse(read("data/natur/flora/illustration-revision-batch04.json"));
const candidates=JSON.parse(read("data/natur/flora/illustration-candidates-batch04.json"));
assert.equal(data.schema,"history-go-flora-revision-batch-v1");
assert.equal(data.batch,"04");
assert.equal(data.items.length,3);
assert.equal(candidates.items.length,3);
assert.equal(data.releaseGate.allowedToPublish,true);

const sandbox={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),sandbox,{timeout:2000});
const published=sandbox.window.HG_NATURE_FLORA_APPROVED;
const catalog=JSON.parse(read("data/runtime/nature-all/flora-001.json")).flatMap(x=>x.kind==="emne_pack"?x.items:[x]);
const photos={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-photographs.js"),photos,{timeout:2000});
const allPhotos=photos.window.HG_NATURE_FLORA_PHOTOS;
const seen=new Set();
for(const p of data.items){
 assert(!seen.has(p.id),"duplicate species");seen.add(p.id);
 assert(p.productionApproval && p.botanicalVisualDecision==="passed","species not accepted");
 assert.equal(p.keyTests.length,4);
 assert(p.sourceReferences.length>=2 && p.sourceReferences.every(s=>s.startsWith("https://")));
 assert.equal(catalog.find(x=>x.id===p.id)?.latin,p.scientificName);
 assert(allPhotos.get(p.id),"documented photo fallback missing: "+p.id);
 const released=published.get(p.id);
 assert(released && released.scientificName===p.scientificName);
 assert.equal(released.src,p.newSrc);
 assert.equal(released.gitBlobSha,p.newGitBlobSha);
 assert.match(p.newSrc,/^bilder\/natur\/flora\/illustrasjonskandidater\/b04\/\d{2}_[a-z]+_v3\.webp$/);
 assert.equal(p.dimensions[0],720);
 assert.equal(p.dimensions[1],1080);
 assert.deepEqual(p.alphaRange,[0,255]);
 const original=bytes(p.currentCandidate);
 const baselineHash=crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+original.length+"\0"),original])).digest("hex");
 assert.equal(baselineHash,p.currentGitBlobSha,"baseline altered: "+p.id);
 const b=bytes(p.newSrc);
 assert.equal(b.length,p.sizeBytes);
 assert.equal(b.toString("ascii",0,4),"RIFF");
 assert.equal(b.toString("ascii",8,12),"WEBP");
 assert.equal(b.toString("ascii",12,16),"VP8X");
 assert((b[20]&0x10)!==0,"alpha transparency missing: "+p.id);
 const git=crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+b.length+"\0"),b])).digest("hex");
 assert.equal(git,p.newGitBlobSha,"v3 file differs: "+p.id);
 assert.equal(crypto.createHash("sha256").update(b).digest("hex"),p.newSha256,"binary provenance differs: "+p.id);
 const candidate=candidates.items.find(c=>c.catalogId===p.id);
 assert(candidate && !candidate.approvedForPublication,"candidate manifest cannot self-release");
 assert.equal(candidate.src,p.newSrc);
 assert.equal(candidate.gitBlobSha,p.newGitBlobSha);
}
assert.equal(published.count,17,"previously accepted images or batch 04 missing");
const gallery=read("flora-illustrasjoner-bolk04.html");
for(const p of data.items)assert(gallery.includes(p.newSrc),"candidate not in gallery: "+p.id);
const review=read("js/ui/flora-illustration-review.js");
assert(review.includes('["01","02","03","04","05","06"]'),"new candidate batch missing in review");
assert(read("flora-illustration-review.html").includes("flora-illustrasjoner-bolk04.html"));
console.log("Flora batch 04: 3 precise original WebP/SHA256 blobs, species reviews, image registry, licensed photo fallback and gallery valid.");
