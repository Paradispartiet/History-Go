import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import vm from "node:vm";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
const doc=JSON.parse(read("data/natur/flora/illustration-quality-varmure-20261104.json")),a=doc.items[0];
assert.equal(doc.baselineApproved,73);
assert.equal(doc.approvedCountAfterRelease,74);
assert.equal(a.catalogId,"emne_flora_varmure");
assert.equal(a.scientificName,"Potentilla verna");
assert.equal(a.existingQuizId,"quiz_nature_flora_varmure");
assert(a.approvedForPublication);
for(const p of ["data/natur/flora/blomster.json","data/runtime/nature-all/flora-001.json"]){
  const e=JSON.parse(read(p)).flatMap(x=>x.kind==="emne_pack"?x.items:[x]).find(x=>x.id===a.catalogId);
  assert(e,"Original species ID missing: "+p);
  assert.equal(e.title,"Vårmure");
  assert.equal(e.latin,"Potentilla verna");
  assert.equal(e.taxonomy.familie,"Rosaceae");
  assert.equal(e.taxonomy.latin_navn,"Potentilla verna");
  assert(e.quiz_ids?.includes("quiz_nature_flora_varmure"));
  assert(e.kjennetegn.some(x=>x.includes("fem")),"Five-petaled Potentilla identification needed");
}
const bytes=fs.readFileSync(new URL("../"+a.src,import.meta.url));
assert.equal(bytes.length,a.sizeBytes);
assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),a.sha256);
assert.equal(crypto.createHash("sha1").update(Buffer.concat([Buffer.from("blob "+bytes.length),Buffer.from([0]),bytes])).digest("hex"),a.gitBlobSha);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.equal(bytes.toString("ascii",12,16),"VP8X");
assert((bytes[20]&0x10)!==0,"Original alpha required");
assert.deepEqual([1+bytes.readUIntLE(24,3),1+bytes.readUIntLE(27,3)],[1024,1536]);
assert(a.visualChecks.blackBackgroundReviewed&&a.visualChecks.originalAlphaVerified);
const env={window:{}};
vm.runInNewContext(read("js/ui/nature-flora-approved.js"),env,{timeout:2000});
const approved=env.window.HG_NATURE_FLORA_APPROVED;
assert.equal(approved.count,74,"Preserve other 73 approved images");
assert.equal(approved.get("emne_flora_varmure")?.scientificName,"Potentilla verna");
assert.equal(approved.get("emne_flora_varmure")?.src,a.src);
assert.equal(approved.get("emne_flora_varmure")?.gitBlobSha,a.gitBlobSha);
assert(a.sourceReferences.length>=3);
console.log("Vårmure #74: verified Potentilla verna taxonomy, existing IDs, exact WebP SHA, alpha and release registry.");
